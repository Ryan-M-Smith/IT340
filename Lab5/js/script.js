const searchInput = document.getElementById("search");
const sunFilter = document.getElementById("sun-filter");
const bloomFilter = document.getElementById("bloom-filter");

function filterPlants() {
	const query = searchInput.value.toLowerCase();
	const sun = sunFilter.value;
	const bloom = bloomFilter.value;

	const filtered = plants.filter((plant) => (
		(query === "" || plant.name.toLowerCase().includes(query))) &&
		(sun === "All" || plant.sunlight === sun) &&
		(bloom === "All" || plant.bloomSeason === bloom
	));

	displayPlants(filtered);
}

function displayPlants(plants) {
	const container = document.getElementById("plant-container")
	container.innerHTML = "";

	if (plants.length === 0) {
		container.innerHTML = "<p>No plants found. Try a different search.</p>";
		return;
	}
	
	plants.forEach((plant) => {
		const plantCard = document.createElement("div");
		plantCard.classList.add("plant-card");

		plantCard.innerHTML = `
			<img src="${plant.image}" alt="${plant.name}" height="100" width="100"/>
			<h2>${plant.name}</h2>
			<p><strong>Scientific Name:</strong> ${plant.scientificName}</p>
			<p>${plant.description}</p>
			<p><strong>Sunlight:</strong> ${plant.sunlight}</p>
			<p><strong>Soil:</strong> ${plant.soil}</p>
			<p><strong>Height:</strong> ${plant.height}</p>
			<p><strong>Bloom Season:</strong> ${plant.bloomSeason}</p>
			<p><strong>Wildlife Benefits:</strong> ${plant.wildlifeBenefits}</p>
			<a class="view-details" href="details.html#${plant.id}">
				View Details
			</a>
		`;

		container.appendChild(plantCard);
	});
}

function displayDetails(plants) {
	plants.forEach((plant) => {
		const plantContainer = document.getElementById("plant-container-details");
		const plantCard = document.createElement("div");
		plantCard.classList.add("plant-card");
		plantCard.id = plant.id;

		plantCard.innerHTML = `
			<img src="${plant.image}" alt="${plant.name}" height="100" width="100"/>
			<h2>${plant.name}</h2>
			<p><strong>Scientific Name:</strong> ${plant.scientificName}</p>
			<p>${plant.longDescription}</p>
			<a class="view-details" href="plants.html">
				Back
			</a>
		`;

		plantContainer.appendChild(plantCard);
	});
}

window.addEventListener("load", () => displayPlants(plants));
window.addEventListener("load", () => displayDetails(plants));

searchInput.addEventListener("input", filterPlants);
sunFilter.addEventListener("change", filterPlants);
bloomFilter.addEventListener("change", filterPlants);